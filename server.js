async function productImage(image) {
  const value = String(image || "").trim();
  if (!value.startsWith("/uploads/")) return value || DEFAULT_PRODUCT_IMAGE;
  const filename = path.basename(value);
  if (!filename || value !== `/uploads/${filename}`)
    return DEFAULT_PRODUCT_IMAGE;
  const uploaded = await db
    .prepare("SELECT file_url FROM image_uploads WHERE public_path = ?")
    .get(value);
  return uploaded?.file_url || DEFAULT_PRODUCT_IMAGE;
}
async function publicProduct(product) {
  const { sales_count, ...rest } = product;
  return {
    ...rest,
    image: await productImage(rest.image),
    salesCount: Number(sales_count || 0),
    isFeatured: Boolean(product.is_featured),
    createdAt: product.created_at,
    updatedAt: product.updated_at,
  };
}
function signUser(user) {
  return jwt.sign({ sub: user.id, role: user.role }, JWT_SECRET, {
    expiresIn: "7d",
  });
}
function auth(required = true) {
  return async (req, res, next) => {
    const token = (req.headers.authorization || "").replace(/^Bearer\s+/i, "");
    if (!token)
      return required
        ? res.status(401).json({ error: "Autentikasi diperlukan." })
        : next();
    try {
      const payload = jwt.verify(token, JWT_SECRET);
      const user = await db
        .prepare(
          "SELECT id, name, email, role, created_at FROM users WHERE id = ?",
        )
        .get(payload.sub);
      if (!user) return res.status(401).json({ error: "Sesi tidak valid." });
      req.user = user;
      next();
    } catch {
      return res
        .status(401)
        .json({ error: "Token tidak valid atau sudah kedaluwarsa." });
    }
  };
}
function adminOnly(req, res, next) {
  if (req.user?.role !== "admin")
    return res.status(403).json({ error: "Akses admin diperlukan." });
  next();
}
function validateProduct(body) {
  const name = String(body.name || "").trim();
  const category = String(body.category || "aksesori")
    .trim()
    .toLowerCase();
  const price = Number(body.price);
  const oldPrice =
    body.oldPrice === "" || body.oldPrice == null
      ? null
      : Number(body.oldPrice);
  const stock = Number(body.stock);
  if (
    !name ||
    !Number.isInteger(price) ||
    price < 0 ||
    (oldPrice !== null && (!Number.isInteger(oldPrice) || oldPrice < 0)) ||
    !Number.isInteger(stock) ||
    stock < 0
  )
    return {
      error:
        "Nama, harga, harga lama, dan stok harus diisi dengan angka yang valid.",
    };
  return {
    value: {
      name,
      slug: String(body.slug || name)
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, ""),
      description: String(body.description || "").trim(),
      category,
      price,
      oldPrice,
      stock,
      image: String(body.image || "/img/product01.png").trim(),
      isFeatured: Boolean(body.isFeatured),
    },
  };
}
async function removeUploadedImage(image) {
  if (
    !image?.startsWith("/uploads/") &&
    !image?.startsWith("https://")
  )
    return;
  const uploaded = await db
    .prepare(
      "SELECT file_id FROM image_uploads WHERE public_path = ? OR file_url = ?",
    )
    .get(image, image);
  if (!uploaded) return;
  try {
    const response = await imageKitFetch(
      `${IMAGEKIT_API_URL}/${encodeURIComponent(uploaded.file_id)}`,
      { method: "DELETE", headers: imageKitHeaders() },
      "delete",
    );
    if (!response.ok && response.status !== 404)
      throw new Error(`Penghapusan ImageKit gagal: ${response.statusText}`);
    await db
      .prepare(
        "DELETE FROM image_uploads WHERE public_path = ? OR file_url = ?",
      )
      .run(image, image);
  } catch (error) {
    console.error(error.message);
  }
}

