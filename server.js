function validateProduct(body) {
  const name = String(body.name || "").trim();
  const categoryId = Number(body.categoryId);
  const brandId = body.brandId == null || body.brandId === '' ? null : Number(body.brandId);
  const price = Number(body.price);
  const oldPrice =
    body.oldPrice === "" || body.oldPrice == null
      ? null
      : Number(body.oldPrice);
  const stock = Number(body.stock);
  const image = String(body.image || DEFAULT_PRODUCT_IMAGE).trim();
  if (image.length > 2000 || /[\\\s\x00-\x1f\x7f]/.test(image) || (!/^\/(?!\/)/.test(image) && !/^https:\/\//i.test(image)))
    return {error:'Gambar harus memakai path internal atau HTTPS.'};
  if (
    !name ||
    !Number.isInteger(categoryId) || categoryId < 1 || categoryId > 2147483647 ||
    (brandId !== null && (!Number.isInteger(brandId) || brandId < 1 || brandId > 2147483647)) ||
    !Number.isInteger(price) || price < 1 || price > 2147483647 ||
    (oldPrice !== null && (!Number.isInteger(oldPrice) || oldPrice < 0 || oldPrice > 2147483647)) ||
    !Number.isInteger(stock) || stock > 2147483647 || stock < 0
  )
    return {
      error:
        "Nama, harga, harga lama, dan stok harus diisi dengan angka yang valid.",
    };
  return {
    value: {
      name,
      slug: String(body.slug || name)
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, ""),
      description: String(body.description || "").trim(),
      categoryId,
      brandId,
      price,
      oldPrice,
      stock,
      image,
      isFeatured: Boolean(body.isFeatured),
    },
  };
}
async function removeUploadedImage(image) {
  if (
    !image?.startsWith("/uploads/") &&
    !image?.startsWith("https://")
  )
    return;
  const uploaded = await db
    .prepare(
      "SELECT file_id FROM image_uploads WHERE public_path = ? OR file_url = ?",
    )
    .get(image, image);
  if (!uploaded) return;
  try {
    const response = await imageKitFetch(
      `${IMAGEKIT_API_URL}/${encodeURIComponent(uploaded.file_id)}`,
      { method: "DELETE", headers: imageKitHeaders() },
      "delete",
    );
    if (!response.ok && response.status !== 404)
      throw new Error(`Penghapusan ImageKit gagal: ${response.statusText}`);
    await db
      .prepare(
        "DELETE FROM image_uploads WHERE public_path = ? OR file_url = ?",
      )
      .run(image, image);
  } catch (error) {
    console.error(error.message);
  }
}

