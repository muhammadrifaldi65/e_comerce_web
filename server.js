const IMAGEKIT_PRIVATE_KEY = process.env.IMAGEKIT_PRIVATE_KEY?.trim();
const IMAGEKIT_FOLDER =
  process.env.IMAGEKIT_FOLDER?.trim() || "/falstore/products";
const IMAGEKIT_UPLOAD_URL = "https://upload.imagekit.io/api/v1/files/upload";
const IMAGEKIT_API_URL = "https://api.imagekit.io/v1/files";
async function imageKitFetch(url, options, operation) {
  try {
    return await fetch(url, options);
  } catch (error) {
    const code = error.cause?.code || error.code || "NETWORK_ERROR";
    const wrapped = new Error(`ImageKit ${operation} gagal diakses (${code}).`);
    wrapped.statusCode = 503;
    throw wrapped;
  }
}

function imageKitHeaders() {
  if (!IMAGEKIT_PRIVATE_KEY)
    throw new Error("IMAGEKIT_PRIVATE_KEY belum dikonfigurasi.");
  return {
    Authorization: `Basic ${Buffer.from(`${IMAGEKIT_PRIVATE_KEY}:`).toString(
      "base64",
    )}`,
  };
}
async function uploadToImageKit(file) {
  const extension = path.extname(file.originalname).toLowerCase() || ".bin";
  const filename = `${crypto.randomUUID()}${extension}`;
  const form = new FormData();
  form.append("file", new Blob([file.buffer], { type: file.mimetype }), filename);
  form.append("fileName", filename);
  form.append("folder", IMAGEKIT_FOLDER);
  form.append("useUniqueFileName", "false");
  const response = await imageKitFetch(
    IMAGEKIT_UPLOAD_URL,
    {
      method: "POST",
      headers: imageKitHeaders(),
      body: form,
    },
    "upload",
  );

  const result = await response.json().catch(() => null);
  if (!response.ok || !result?.url || !result?.fileId)
    throw new Error(
      `Upload ImageKit gagal: ${result?.message || response.statusText}`,
    );
  const publicPath = `/uploads/${crypto.randomUUID()}${extension}`;
  await db
    .prepare(
      "INSERT INTO image_uploads (public_path, file_id, file_url) VALUES (?, ?, ?)",
    )
    .run(publicPath, result.fileId, result.url);
  return {
    publicPath,
    imageKitUrl: result.url,
    filename,
    size: file.size,
  };
}

