function postgresSql(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

class PostgresStatement {
  constructor(owner, sql, client = owner.pool) {
    this.owner = owner;
    this.sql = postgresSql(sql);
    this.client = client;
  }
  async all(...params) {
    const result = await this.client.query(this.sql, params);
    return result.rows;
  }
  async get(...params) {
    const rows = await this.all(...params);
    return rows[0];
  }
  async run(...params) {
    const sql =
      /^\s*INSERT\b/i.test(this.sql) && !/\bRETURNING\b/i.test(this.sql)
        ? `${this.sql} RETURNING id`
        : this.sql;
    const result = await this.client.query(sql, params);
    return {
      lastInsertRowid: result.rows[0]?.id ?? 0,
      changes: result.rowCount,
    };
  }
}

class PostgresDatabase {
  constructor(connectionString) {
    this.pool = new Pool({
      connectionString,
      ssl: { rejectUnauthorized: false },
    });
  }
  async init() {
    await this.pool.query("SELECT 1");
    return this;
  }
  async exec(sql) {
    return this.pool.query(sql);
  }
  prepare(sql) {
    return new PostgresStatement(this, sql);
  }
  async transaction(callback) {
    const client = await this.pool.connect();
    try {
      await client.query("BEGIN");
      const value = await callback({
        prepare: (sql) => new PostgresStatement(this, sql, client),
      });
      await client.query("COMMIT");
      return value;
    } catch (error) {
      await client.query("ROLLBACK");
      throw error;
    } finally {
      client.release();
    }
  }
  async close() {
    await this.pool.end();
  }
}



